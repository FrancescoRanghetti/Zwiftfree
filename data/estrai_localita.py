#!/usr/bin/env python3
"""
Extracts Ticino localities (OSM place=city/town/village/hamlet) for place search.

Uses the files already downloaded by scarica_ticino.py (cache/switzerland-latest.osm.pbf and
cache/ticino_boundary.geojson) and writes the Flyway seed migration of the backend.

Usage:  python estrai_localita.py --cache cache --out ../backend/Zwiftfree-be/src/main/resources/db/migration/V3__places_seed.sql
Requires: osmium shapely
Data: © OpenStreetMap contributors (ODbL)
"""
import argparse
import json
import os

import osmium
from shapely.geometry import Point, shape
from shapely.prepared import prep

PLACE_RANK = {"city": 1, "town": 2, "village": 3, "hamlet": 4}


class PlaceHandler(osmium.SimpleHandler):
    def __init__(self, boundary):
        super().__init__()
        self.boundary = boundary
        self.places = []

    def node(self, n):
        place = n.tags.get("place")
        name = n.tags.get("name")
        if place not in PLACE_RANK or not name or not n.location.valid():
            return
        lon, lat = n.location.lon, n.location.lat
        if not self.boundary.contains(Point(lon, lat)):
            return
        pop = n.tags.get("population", "")
        self.places.append({
            "osm_id": n.id,
            "name": name,
            "kind": place,
            "rank": PLACE_RANK[place],
            "population": int(pop) if pop.isdigit() else None,
            "lon": round(lon, 6),
            "lat": round(lat, 6),
        })


def sql_str(s):
    return "'" + s.replace("'", "''") + "'"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", default="cache")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    with open(os.path.join(a.cache, "ticino_boundary.geojson")) as f:
        gj = json.load(f)
    geom = shape(gj["features"][0]["geometry"] if "features" in gj else gj.get("geometry", gj))
    handler = PlaceHandler(prep(geom.buffer(0.002)))
    handler.apply_file(os.path.join(a.cache, "switzerland-latest.osm.pbf"))

    places = sorted(handler.places, key=lambda p: (p["rank"], p["name"]))
    with open(a.out, "w", encoding="utf-8") as out:
        out.write("-- Generated by data/estrai_localita.py from OpenStreetMap (© OpenStreetMap contributors, ODbL).\n")
        out.write(f"-- {len(places)} localities of Canton Ticino. Do not edit by hand.\n\n")
        out.write("INSERT INTO places (osm_id, name, kind, rank, population, lon, lat) VALUES\n")
        rows = []
        for p in places:
            pop = "NULL" if p["population"] is None else str(p["population"])
            rows.append(f"  ({p['osm_id']}, {sql_str(p['name'])}, {sql_str(p['kind'])}, {p['rank']}, "
                        f"{pop}, {p['lon']}, {p['lat']})")
        out.write(",\n".join(rows))
        out.write("\nON CONFLICT (osm_id) DO NOTHING;\n")
    counts = {}
    for p in places:
        counts[p["kind"]] = counts.get(p["kind"], 0) + 1
    print(f"{len(places)} places written to {a.out}: {counts}")


if __name__ == "__main__":
    main()
