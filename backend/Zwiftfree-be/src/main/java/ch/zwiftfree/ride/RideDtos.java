package ch.zwiftfree.ride;

import jakarta.validation.Valid;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.PositiveOrZero;
import jakarta.validation.constraints.Size;
import java.time.Instant;
import java.util.List;
import java.util.Map;
import java.util.UUID;

public final class RideDtos {

    private RideDtos() {
    }

    public enum RideMode {
        TRAINER, SIMULATOR
    }

    public enum RideStatus {
        IN_PROGRESS, COMPLETED, ABANDONED
    }

    public enum RideEventType {
        PEE_BREAK_START, PEE_BREAK_END, CRASH, RECOVERED, SEGMENT_DONE, PAUSE, RESUME
    }

    /** @param routeId saved route being ridden, null for free rides and unsaved plans */
    public record CreateRide(UUID routeId, @NotNull(message = "Modalità obbligatoria") RideMode mode) {
    }

    /**
     * One second of riding.
     *
     * @param t seconds of ride clock since the start (the clock stops while paused)
     * @param edgeOffsetM position along the edge measured from its source node
     */
    public record SampleDto(
            @Min(0) @Max(86_400) int t,
            Double distanceM,
            Double lat,
            Double lon,
            Double ele,
            Double grade,
            @Min(0) @Max(3000) Integer power,
            @Min(0) @Max(300) Integer cadence,
            @Min(0) @Max(260) Integer hr,
            @Min(0) @Max(200) Double speedKmh,
            @Size(max = 20) String avatarState,
            Long edgeId,
            Double edgeOffsetM) {
    }

    /**
     * An edge entered during the ride, in order (seq starts at 0).
     *
     * @param startM ride distance when the edge was entered (needed to time segments; older clients omit it)
     */
    public record RideEdgeDto(@Min(0) int seq, long edgeId, @Min(-1) @Max(1) int direction,
            @PositiveOrZero Double startM) {
    }

    /** A block of samples, sent every 30 s. Re-sending the same block is harmless. */
    public record SamplesBatch(
            @NotNull @Size(max = 900) List<@Valid @NotNull SampleDto> samples,
            @Size(max = 5000) List<@Valid @NotNull RideEdgeDto> edges) {
    }

    /** @param id generated by the client so that re-sending an event does not duplicate it */
    public record EventDto(
            @NotNull UUID id,
            @Min(0) int t,
            @NotNull RideEventType type,
            Double distanceM,
            Map<String, Object> payload) {
    }

    public record EventsBatch(@NotNull @Size(max = 200) List<@Valid @NotNull EventDto> events) {
    }

    public record RideSummary(
            UUID id,
            UUID routeId,
            String routeName,
            Instant startedAt,
            Instant endedAt,
            RideStatus status,
            RideMode mode,
            Double distanceM,
            Integer movingTimeS,
            Integer elapsedTimeS,
            Double ascentM,
            Integer avgPower,
            Integer maxPower,
            Integer normalizedPower,
            Integer avgHr,
            Integer maxHr,
            Integer avgCadence,
            Double avgSpeedKmh,
            Double kj,
            Double tss,
            Double intensityFactor,
            int peeBreaks,
            int crashes) {
    }

    /**
     * @param records personal records set by this ride when it was completed
     * @param segmentEfforts timed segments ridden in full during this ride
     */
    public record RideDetail(RideSummary ride, List<EventDto> events, List<NewRecord> records,
            List<SegmentEffortDto> segmentEfforts) {
    }

    /**
     * @param metric BEST_5S, BEST_1MIN, BEST_5MIN, BEST_20MIN, BEST_60MIN (W), LONGEST_RIDE, MOST_ASCENT (m) or
     *     segment:&lt;id&gt; (s)
     * @param previous the record before this ride, null if it is the first value
     */
    public record NewRecord(String metric, double value, Double previous) {
    }

    /**
     * @param personalBest whether this is (still) the user's best time on the segment
     * @param rank position among all the user's efforts on the segment (1 = best)
     */
    public record SegmentEffortDto(UUID segmentId, String name, String type, double lengthM, Double avgGrade,
            int elapsedS, Integer avgPower, boolean personalBest, int rank) {
    }

    /** Samples in columns (much smaller JSON than one object per second). */
    public record SamplesColumns(
            int[] t,
            double[] distanceM,
            Double[] lat,
            Double[] lon,
            Double[] ele,
            Double[] grade,
            Integer[] power,
            Integer[] cadence,
            Integer[] hr,
            Double[] speedKmh,
            String[] avatarState) {
    }

    public record Page<T>(List<T> content, int page, int size, long totalElements, int totalPages) {
    }

    /** @param geojson FeatureCollection of the explored roads (simplified, 2D) */
    public record Explored(int exploredEdges, int totalEdges, double exploredKm, double totalKm, double percent,
            Map<String, Object> geojson) {
    }
}
